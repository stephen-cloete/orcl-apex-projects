--------------------------------------------------------------------------------
-- Data Explorer - 01_tables.sql   (run as DATAEXP)
-- Idempotent: each object is created only when missing ("already exists" errors ignored).
--------------------------------------------------------------------------------
create or replace procedure dx_ddl(p_sql in varchar2) authid current_user is
begin
  execute immediate p_sql;
exception
  when others then
    -- -955 name already used, -2260/-2261 key exists, -1430 column exists, -2275 fk exists
    if sqlcode not in (-955, -2260, -2261, -1430, -2275, -1408) then raise; end if;
end dx_ddl;
/

begin
  dx_ddl('
create table dx_settings (
  setting_key   varchar2(64)   not null constraint dx_settings_pk primary key,
  setting_value varchar2(4000),
  description   varchar2(400)
)');

  dx_ddl('
create table dx_data_sources (
  source_id      number generated by default on null as identity constraint dx_data_sources_pk primary key,
  name           varchar2(128)  not null constraint dx_data_sources_uk unique,
  source_type    varchar2(10)   default ''SCHEMA'' not null
                 constraint dx_data_sources_type_ck check (source_type in (''SCHEMA'',''REST'')),
  schema_owner   varchar2(128),
  rest_url       varchar2(2000),
  rest_row_path  varchar2(400)  default ''$[*]'',
  rest_columns   varchar2(4000),
  view_name      varchar2(128),
  description    varchar2(1000),
  is_enabled     varchar2(1)    default ''Y'' not null constraint dx_data_sources_en_ck check (is_enabled in (''Y'',''N'')),
  refreshed_at   timestamp with time zone,
  last_status    varchar2(4000),
  created_by     varchar2(255)  default coalesce(sys_context(''APEX$SESSION'',''APP_USER''), user) not null,
  created_at     timestamp with time zone default systimestamp not null,
  constraint dx_data_sources_ck check (
       (source_type = ''SCHEMA'' and schema_owner is not null)
    or (source_type = ''REST''   and rest_url is not null and rest_columns is not null))
)');

  dx_ddl('
create table dx_rest_cache (
  source_id   number not null constraint dx_rest_cache_pk primary key
              constraint dx_rest_cache_fk references dx_data_sources(source_id) on delete cascade,
  payload     clob constraint dx_rest_cache_json_ck check (payload is json),
  http_status number,
  fetched_at  timestamp with time zone default systimestamp not null
)');

  dx_ddl('
create table dx_saved_queries (
  query_id    number generated by default on null as identity constraint dx_saved_queries_pk primary key,
  title       varchar2(200)  not null,
  description varchar2(1000),
  sql_text    clob           not null,
  owner       varchar2(255)  default coalesce(sys_context(''APEX$SESSION'',''APP_USER''), user) not null,
  is_shared   varchar2(1)    default ''N'' not null constraint dx_saved_queries_sh_ck check (is_shared in (''Y'',''N'')),
  run_count   number         default 0 not null,
  last_run_at timestamp with time zone,
  created_at  timestamp with time zone default systimestamp not null,
  updated_at  timestamp with time zone default systimestamp not null
)');

  dx_ddl('
create table dx_query_log (
  log_id     number generated by default on null as identity constraint dx_query_log_pk primary key,
  username   varchar2(255) not null,
  query_id   number,
  sql_text   varchar2(4000),
  status     varchar2(10)  not null constraint dx_query_log_st_ck check (status in (''OK'',''ERROR'',''BLOCKED'')),
  row_count  number,
  elapsed_ms number,
  error_msg  varchar2(4000),
  run_at     timestamp with time zone default systimestamp not null
)');

  dx_ddl('create index dx_query_log_user_ix on dx_query_log (username, run_at)');
  dx_ddl('create index dx_saved_queries_owner_ix on dx_saved_queries (owner)');
end;
/
