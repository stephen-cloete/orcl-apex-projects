def q(s):  # SQL literal
    return "'" + s.replace("'", "''") + "'"
def join(lines):
    if isinstance(lines, str): lines = lines.split('\n')
    return "wwv_flow_string.join(wwv_flow_t_varchar2(\n" + ",\n".join(q(l) for l in lines) + "))"
def attrs(d):
    items = ",\n".join(f"  {q(k)}, {q(v)}" for k, v in sorted(d.items()))
    return f"wwv_flow_t_plugin_attributes(wwv_flow_t_varchar2(\n{items})).to_clob"
def call(proc, **kw):
    parts = []
    for k, v in kw.items():
        parts.append(f"p_{k}=>{v}")
    return f"{proc}(\n " + "\n,".join(parts) + "\n);\n"
