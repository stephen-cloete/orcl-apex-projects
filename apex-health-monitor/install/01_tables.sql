create table hm_targets (
  target_id        number generated by default on null as identity
                   constraint hm_targets_pk primary key,
  name             varchar2(100 char)  not null constraint hm_targets_uk unique,
  target_type      varchar2(10 char)   default 'HTTP' not null
                   constraint hm_targets_type_ck check (target_type in ('HTTP','SQL')),
  endpoint         varchar2(1000 char) not null,      -- URL for HTTP, query for SQL
  expected_status  number(3)           default 200,   -- HTTP only
  warn_threshold   number,                            -- HTTP: ms, SQL: value
  crit_threshold   number,                            -- HTTP: ms, SQL: value
  timeout_sec      number(3)           default 15 not null,
  interval_min     number(4)           default 5  not null,
  enabled_yn       varchar2(1 char)    default 'Y' not null
                   constraint hm_targets_enabled_ck check (enabled_yn in ('Y','N')),
  description      varchar2(400 char),
  created_on       timestamp with time zone default systimestamp not null,
  created_by       varchar2(128 char)  default coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  updated_on       timestamp with time zone,
  updated_by       varchar2(128 char)
);

comment on table  hm_targets is 'Endpoints and database checks monitored by apex-health-monitor';
comment on column hm_targets.endpoint is 'HTTPS URL (HTTP) or a single-value SELECT (SQL)';

create table hm_checks (
  check_id         number generated always as identity constraint hm_checks_pk primary key,
  target_id        number not null
                   constraint hm_checks_target_fk references hm_targets on delete cascade,
  checked_at       timestamp with time zone default systimestamp not null,
  status           varchar2(12 char) not null
                   constraint hm_checks_status_ck check (status in ('UP','DEGRADED','DOWN','UNREACHABLE')),
  http_status      number(3),
  response_ms      number,
  metric_value     number,
  message          varchar2(1000 char)
);

create index hm_checks_target_ix on hm_checks (target_id, checked_at desc);
create index hm_checks_time_ix   on hm_checks (checked_at);

create table hm_incidents (
  incident_id      number generated always as identity constraint hm_incidents_pk primary key,
  target_id        number not null
                   constraint hm_incidents_target_fk references hm_targets on delete cascade,
  started_at       timestamp with time zone default systimestamp not null,
  resolved_at      timestamp with time zone,
  severity         varchar2(12 char) not null
                   constraint hm_incidents_sev_ck check (severity in ('DEGRADED','DOWN','UNREACHABLE')),
  first_message    varchar2(1000 char),
  last_message     varchar2(1000 char),
  check_count      number default 1 not null
);

create index hm_incidents_target_ix on hm_incidents (target_id, resolved_at);
